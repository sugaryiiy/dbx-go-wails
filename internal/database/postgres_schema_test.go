func TestReferenceableIndexes(t *testing.T) {
	cases := []struct {
		name  string
		index record
		want  bool
	}{
		{"ordinary", record{"is_unique": true, "columns": []string{"Mixed Case"}}, true},
		{"primary", record{"is_unique": true, "is_primary": true, "columns": []string{"b", "a"}, "included_columns": []string{"data"}}, true},
		{"expression", record{"is_unique": true, "columns": []string{"lower(code)"}, "key_is_expression": []bool{true}}, false},
		{"partial", record{"is_unique": true, "columns": []string{"id"}, "filter": "id > 0"}, false},
		{"invalid", record{"is_unique": true, "columns": []string{"id"}, "is_valid": false}, false},
		{"deferrable", record{"is_unique": true, "columns": []string{"id"}, "is_immediate": false}, false},
		{"empty expression", record{"is_unique": true, "columns": []string{""}}, false},
		{"nonunique", record{"is_unique": false, "columns": []string{"id"}}, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := referenceableIndex(tc.index); got != tc.want {
				t.Fatalf("referenceable=%t want=%t", got, tc.want)
			}
		})
	}
}

func TestPostgresDDLQuoting(t *testing.T) {
	if got := pgQualified(`odd"schema`, `x"; DROP TABLE y;--`); got != `"odd""schema"."x""; DROP TABLE y;--"` {
		t.Fatal(got)
	}
	if got := pgLiteral("quote' slash\\ newline\n"); got != "E'quote'' slash\\\\ newline\n'" {
		t.Fatal(got)
	}
	options, err := pgOptions(`["fillfactor=80","toast.autovacuum_enabled=false","custom=a'b\\c"]`)
	if err != nil {
		t.Fatal(err)
	}
	if options != `"fillfactor" = E'80', "toast"."autovacuum_enabled" = E'false', "custom" = E'a''b\\c'` {
		t.Fatal(options)
	}
	if _, err = pgOptions(`["malformed"]`); err == nil {
		t.Fatal("accepted malformed catalog option")
	}
}

// This integration suite only runs when a disposable PostgreSQL DSN is supplied.
// It creates its own schema and never reads or changes pre-existing user tables.
func postgresSchemaFixture(t *testing.T) (context.Context, *sql.DB, string) {
	t.Helper()
	dsn := os.Getenv("DBX_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set DBX_TEST_POSTGRES_DSN to a disposable PostgreSQL 12+ database")
	}
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	t.Cleanup(cancel)
	if err = db.PingContext(ctx); err != nil {
		t.Fatal(err)
	}
	schema := fmt.Sprintf("dbx_schema_%d", time.Now().UnixNano())
	if _, err = db.ExecContext(ctx, "CREATE SCHEMA "+pgIdent(schema)); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		cleanup, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if _, err := db.ExecContext(cleanup, "DROP SCHEMA "+pgIdent(schema)+" CASCADE"); err != nil {
			t.Errorf("cleanup: %v", err)
		}
	})
	return ctx, db, schema
}

func pgTestExec(t *testing.T, ctx context.Context, db *sql.DB, statement string) {
	t.Helper()
	if _, err := db.ExecContext(ctx, statement); err != nil {
		t.Fatalf("%s\n%v", statement, err)
	}
}
func pgTestDDL(t *testing.T, ctx context.Context, db *sql.DB, schema, table, kind string) string {
	t.Helper()
	ddl, err := objectDDL(ctx, db, "postgres", "", schema, table, kind)
	if err != nil {
		t.Fatal(err)
	}
	return ddl
}

func TestPostgresSchemaRoundTrip(t *testing.T) {
	ctx, db, schema := postgresSchemaFixture(t)
	parent := pgQualified(schema, "parent")
	tableName := `Orders " v1`
	table := pgQualified(schema, tableName)
	pgTestExec(t, ctx, db, "CREATE TABLE "+parent+" (a integer,b integer); CREATE UNIQUE INDEX parent_ref ON "+parent+"(b,a)")
	pgTestExec(t, ctx, db, "CREATE TYPE "+pgQualified(schema, "order_state")+" AS ENUM ('pending','done')")
	pgTestExec(t, ctx, db, "CREATE TABLE "+table+` (
 id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5 MINVALUE 5 MAXVALUE 100000 CACHE 3 CYCLE),
 serial_no bigserial NOT NULL,
 "Display Name" varchar(100) COLLATE "C" NOT NULL DEFAULT E'O''Reilly\\books',
 amount numeric(12,2) NOT NULL DEFAULT 2.50,
 state `+pgQualified(schema, "order_state")+` DEFAULT 'pending',
 computed numeric GENERATED ALWAYS AS (amount * 2) STORED,
 a integer,b integer,
 CONSTRAINT orders_pk PRIMARY KEY(id),
 CONSTRAINT orders_serial_unique UNIQUE(serial_no) DEFERRABLE INITIALLY DEFERRED,
 CONSTRAINT amount_check CHECK(amount >= 0),
 CONSTRAINT composite_fk FOREIGN KEY(b,a) REFERENCES `+parent+`(b,a) ON UPDATE CASCADE ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
 ) WITH(fillfactor=80)`)
	pgTestExec(t, ctx, db, "CREATE INDEX expression_idx ON "+table+` ((lower("Display Name")) text_pattern_ops DESC NULLS LAST, amount ASC NULLS FIRST) INCLUDE (a,b) WHERE amount > 1`)
	pgTestExec(t, ctx, db, "CREATE UNIQUE INDEX partial_unique ON "+table+"(a) WHERE a IS NOT NULL")
	pgTestExec(t, ctx, db, "CREATE INDEX long_expression ON "+table+` ((lower("Display Name" || 'this literal deliberately makes the expression exceed PostgreSQL name length sixty-three')))`)
	pgTestExec(t, ctx, db, "ALTER TABLE "+table+" ADD CONSTRAINT amount_not_valid CHECK(amount < 10000) NOT VALID")
	pgTestExec(t, ctx, db, "ALTER TABLE "+table+" REPLICA IDENTITY FULL")
	pgTestExec(t, ctx, db, "COMMENT ON TABLE "+table+" IS "+pgLiteral("table ' comment\\path\nnew line")+"; COMMENT ON COLUMN "+table+`."Display Name" IS `+pgLiteral("column ' comment\\")+"; COMMENT ON INDEX "+pgQualified(schema, "expression_idx")+" IS "+pgLiteral("expression comment")+"; COMMENT ON CONSTRAINT composite_fk ON "+table+" IS "+pgLiteral("foreign comment"))
	pgTestExec(t, ctx, db, "ALTER TABLE "+table+` ALTER COLUMN "Display Name" SET STORAGE EXTERNAL; ALTER TABLE `+table+` ALTER COLUMN amount SET STATISTICS 123`)

	beforeCols, err := columns(ctx, db, "postgres", "", schema, tableName)
	if err != nil {
		t.Fatal(err)
	}
	beforeIndexes, err := indexes(ctx, db, "postgres", "", schema, tableName)
	if err != nil {
		t.Fatal(err)
	}
	byName := map[string]record{}
	for _, idx := range beforeIndexes {
		byName[valueString(idx["name"])] = idx
	}
	if got := valueString(byName["long_expression"]["columns"].([]string)[0]); len(got) <= 63 || !strings.Contains(got, "sixty-three") {
		t.Fatalf("expression truncated to name type: %s", got)
	}
	expression := byName["expression_idx"]
	if !reflect.DeepEqual(expression["columns"], []string{`lower(("Display Name")::text)`, "amount"}) {
		t.Fatalf("expression/column provenance: %#v", expression)
	}
	if !reflect.DeepEqual(expression["key_is_expression"], []bool{true, false}) || !reflect.DeepEqual(expression["included_columns"], []string{"a", "b"}) || !reflect.DeepEqual(expression["key_options"], []int64{1, 2}) {
		t.Fatalf("ordered keys, flags and INCLUDE lost: %#v", expression)
	}
	if !reflect.DeepEqual(expression["column_opclasses"], []any{"pg_catalog.text_pattern_ops", nil}) {
		t.Fatalf("opclasses lost: %#v", expression)
	}
	if referenceableIndex(byName["partial_unique"]) || referenceableIndex(byName["orders_serial_unique"]) {
		t.Fatal("partial or deferrable index is referenceable")
	}
	parentIndexes, err := indexes(ctx, db, "postgres", "", schema, "parent")
	if err != nil {
		t.Fatal(err)
	}
	if len(parentIndexes) != 1 || valueBool(parentIndexes[0]["constraint_backed"]) || !reflect.DeepEqual(parentIndexes[0]["columns"], []string{"b", "a"}) {
		t.Fatalf("FK wrongly owns referenced standalone index: %#v", parentIndexes)
	}
	beforeFK, err := foreignKeys(ctx, db, "postgres", "", schema, tableName)
	if err != nil {
		t.Fatal(err)
	}
	if len(beforeFK) != 2 || beforeFK[0]["column"] != "b" || beforeFK[0]["ref_column"] != "b" || beforeFK[1]["column"] != "a" || beforeFK[0]["ref_schema"] != schema || beforeFK[0]["on_update"] != "CASCADE" || beforeFK[0]["on_delete"] != "SET NULL" {
		t.Fatalf("composite foreign key: %#v", beforeFK)
	}
	ddl := pgTestDDL(t, ctx, db, schema, tableName, "")
	for _, fragment := range []string{"GENERATED BY DEFAULT AS IDENTITY", "GENERATED ALWAYS AS", "CREATE SEQUENCE", "DEFERRABLE INITIALLY DEFERRED", "NOT VALID", "INCLUDE (a, b)", "REPLICA IDENTITY FULL", "SET STORAGE EXTERNAL", "SET STATISTICS 123", "COMMENT ON CONSTRAINT"} {
		if !strings.Contains(ddl, fragment) {
			t.Fatalf("DDL missing %q:\n%s", fragment, ddl)
		}
	}
	// Same schema/name round-trip also checks that owned sequences and identity
	// names are recreated after DROP removes the original dependent sequences.
	pgTestExec(t, ctx, db, "DROP TABLE "+table)
	pgTestExec(t, ctx, db, ddl)
	afterCols, err := columns(ctx, db, "postgres", "", schema, tableName)
	if err != nil {
		t.Fatal(err)
	}
	afterIndexes, err := indexes(ctx, db, "postgres", "", schema, tableName)
	if err != nil {
		t.Fatal(err)
	}
	afterFK, err := foreignKeys(ctx, db, "postgres", "", schema, tableName)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(beforeCols, afterCols) {
		t.Fatalf("columns changed:\nbefore %#v\nafter %#v", beforeCols, afterCols)
	}
	if !reflect.DeepEqual(beforeIndexes, afterIndexes) {
		t.Fatalf("indexes changed:\nbefore %#v\nafter %#v", beforeIndexes, afterIndexes)
	}
	if !reflect.DeepEqual(beforeFK, afterFK) {
		t.Fatalf("foreign keys changed:\nbefore %#v\nafter %#v", beforeFK, afterFK)
	}
	if afterDDL := pgTestDDL(t, ctx, db, schema, tableName, "TABLE"); afterDDL != ddl {
		t.Fatalf("DDL is not stable after recreate:\nbefore %s\nafter %s", ddl, afterDDL)
	}
	var id, serial int64
	var computed string
	if err = db.QueryRowContext(ctx, "INSERT INTO "+table+`("Display Name") VALUES ('ok') RETURNING id,serial_no,computed::text`).Scan(&id, &serial, &computed); err != nil {
		t.Fatal(err)
	}
	if id != 10 || serial != 1 || computed != "5.00" {
		t.Fatalf("identity/default/generated behavior lost: %d %d %q", id, serial, computed)
	}
	if _, err = db.ExecContext(ctx, "INSERT INTO "+table+"(a,b) VALUES(99,99)"); err == nil {
		t.Fatal("foreign key not enforced after round-trip")
	}
}

func TestPostgresViewAndMaterializedViewDDL(t *testing.T) {
	ctx, db, schema := postgresSchemaFixture(t)
	base := pgQualified(schema, "base")
	pgTestExec(t, ctx, db, "CREATE TABLE "+base+"(id integer PRIMARY KEY,label text); INSERT INTO "+base+" VALUES (1,'one')")
	for _, tc := range []struct{ name, kind, sql string }{
		{"view_alias", "VIEW", "CREATE VIEW " + pgQualified(schema, "view_alias") + `("Record ID",label) WITH (security_barrier=true, check_option=local) AS SELECT id,label FROM ` + base + " WHERE id>0"},
		{"materialized_alias", "MATERIALIZED_VIEW", "CREATE MATERIALIZED VIEW " + pgQualified(schema, "materialized_alias") + `("Record ID",label) WITH (fillfactor=75) AS SELECT id,label FROM ` + base + " WITH NO DATA"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			pgTestExec(t, ctx, db, tc.sql)
			name := pgQualified(schema, tc.name)
			kind := strings.ReplaceAll(tc.kind, "_", " ")
			pgTestExec(t, ctx, db, "COMMENT ON "+kind+" "+name+" IS "+pgLiteral("object ' \\ comment")+"; COMMENT ON COLUMN "+name+`.label IS ''`)
			if tc.kind == "VIEW" {
				pgTestExec(t, ctx, db, "ALTER VIEW "+name+" ALTER COLUMN label SET DEFAULT 'from view'")
			} else {
				pgTestExec(t, ctx, db, "CREATE UNIQUE INDEX materialized_key ON "+name+`("Record ID")`)
			}
			ddl := pgTestDDL(t, ctx, db, schema, tc.name, "")
			pgTestExec(t, ctx, db, "DROP "+kind+" "+name)
			pgTestExec(t, ctx, db, ddl)
			if got := pgTestDDL(t, ctx, db, schema, tc.name, tc.kind); got != ddl {
				t.Fatalf("view DDL changed:\n%s\n%s", ddl, got)
			}
			if tc.kind == "MATERIALIZED_VIEW" {
				pgTestExec(t, ctx, db, "REFRESH MATERIALIZED VIEW "+name)
			}
			var label string
			if err := db.QueryRowContext(ctx, "SELECT label FROM "+name).Scan(&label); err != nil || label != "one" {
				t.Fatalf("view query: %q %v", label, err)
			}
		})
	}
}

func TestPostgresUnsupportedDDLAndParameterization(t *testing.T) {
	ctx, db, schema := postgresSchemaFixture(t)
	table := pgQualified(schema, "guarded")
	pgTestExec(t, ctx, db, "CREATE TABLE "+table+"(id integer)")
	if _, err := objectDDL(ctx, db, "postgres", "", schema, "guarded' OR 1=1 --", ""); !errors.Is(err, sql.ErrNoRows) {
		t.Fatalf("identifier lookup was not parameterized: %v", err)
	}
	if _, err := objectDDL(ctx, db, "postgres", "", schema, "guarded", "VIEW"); err == nil {
		t.Fatal("accepted wrong relation type")
	}
	pgTestExec(t, ctx, db, "ALTER TABLE "+table+" ENABLE ROW LEVEL SECURITY")
	if ddl, err := objectDDL(ctx, db, "postgres", "", schema, "guarded", ""); !errors.Is(err, ErrUnsupported) || ddl != "" {
		t.Fatalf("silently omitted RLS: %s %v", ddl, err)
	}
	partitioned := pgQualified(schema, "partitioned")
	pgTestExec(t, ctx, db, "CREATE TABLE "+partitioned+"(id integer) PARTITION BY RANGE(id)")
	if _, err := objectDDL(ctx, db, "postgres", "", schema, "partitioned", ""); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("silently lost partitions: %v", err)
	}
	inherited := pgQualified(schema, "inherited")
	pgTestExec(t, ctx, db, "CREATE TABLE "+inherited+"(extra text) INHERITS ("+table+")")
	if _, err := objectDDL(ctx, db, "postgres", "", schema, "inherited", ""); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("silently lost inheritance: %v", err)
	}
}

func TestPostgresSelfReferenceAndPrimaryInclude(t *testing.T) {
	ctx, db, schema := postgresSchemaFixture(t)
	self := pgQualified(schema, "self_ref")
	pgTestExec(t, ctx, db, "CREATE TABLE "+self+` ("Key Value" integer,payload text,parent integer); CREATE UNIQUE INDEX self_target ON `+self+` ("Key Value") INCLUDE(payload); ALTER TABLE `+self+` ADD CONSTRAINT self_fk FOREIGN KEY(parent) REFERENCES `+self+`("Key Value")`)
	ddl := pgTestDDL(t, ctx, db, schema, "self_ref", "")
	if strings.Index(ddl, "CREATE UNIQUE INDEX") > strings.Index(ddl, `ADD CONSTRAINT "self_fk"`) {
		t.Fatal("self FK emitted before its referenced standalone index")
	}
	pgTestExec(t, ctx, db, "DROP TABLE "+self)
	pgTestExec(t, ctx, db, ddl)
	pgTestExec(t, ctx, db, "INSERT INTO "+self+`("Key Value") VALUES (1); INSERT INTO `+self+`("Key Value",parent) VALUES(2,1)`)
	if _, err := db.ExecContext(ctx, "INSERT INTO "+self+`("Key Value",parent) VALUES(3,9)`); err == nil {
		t.Fatal("self foreign key was lost")
	}
	included := pgQualified(schema, "pk_included")
	pgTestExec(t, ctx, db, "CREATE TABLE "+included+"(id integer,cover text, CONSTRAINT included_pk PRIMARY KEY(id) INCLUDE(cover))")
	cols, err := columns(ctx, db, "postgres", "", schema, "pk_included")
	if err != nil {
		t.Fatal(err)
	}
	if len(cols) != 2 || !valueBool(cols[0]["is_primary_key"]) || valueBool(cols[1]["is_primary_key"]) {
		t.Fatalf("INCLUDE column is incorrectly a primary key: %#v", cols)
	}
	idx, err := indexes(ctx, db, "postgres", "", schema, "pk_included")
	if err != nil {
		t.Fatal(err)
	}
	if len(idx) != 1 || !reflect.DeepEqual(idx[0]["columns"], []string{"id"}) || !reflect.DeepEqual(idx[0]["included_columns"], []string{"cover"}) {
		t.Fatal(idx)
	}
}

func TestPostgresDDLDefaultStatistics(t *testing.T) {
	ctx, db, schema := postgresSchemaFixture(t)
	table := pgQualified(schema, "statistics_targets")
	pgTestExec(t, ctx, db, "CREATE TABLE "+table+"(defaulted integer,disabled integer,custom integer); ALTER TABLE "+table+" ALTER COLUMN disabled SET STATISTICS 0; ALTER TABLE "+table+" ALTER COLUMN custom SET STATISTICS 250")
	catalog := func() []record {
		t.Helper()
		result, err := records(ctx, db, `SELECT a.attname,a.attstattarget FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname='statistics_targets' AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`, schema)
		if err != nil {
			t.Fatal(err)
		}
		return result
	}
	before := catalog()
	ddl := pgTestDDL(t, ctx, db, schema, "statistics_targets", "")
	if strings.Contains(ddl, `ALTER COLUMN "defaulted" SET STATISTICS`) {
		t.Fatalf("default statistics changed into an explicit target:\n%s", ddl)
	}
	if !strings.Contains(ddl, `ALTER COLUMN "disabled" SET STATISTICS 0`) || !strings.Contains(ddl, `ALTER COLUMN "custom" SET STATISTICS 250`) {
		t.Fatalf("explicit statistics target was lost:\n%s", ddl)
	}
	if !strings.Contains(ddl, "CREATE TABLE "+table) {
		t.Fatalf("relation name lost schema qualification:\n%s", ddl)
	}
	pgTestExec(t, ctx, db, "DROP TABLE "+table)
	pgTestExec(t, ctx, db, ddl)
	if after := catalog(); !reflect.DeepEqual(before, after) {
		t.Fatalf("catalog statistics changed: before=%#v after=%#v", before, after)
	}
}

package server

import (
	"errors"
	"fmt"
	"net/http"
	"regexp"
	"strings"
)

var schemaTypePattern = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_ .]*(?:\([0-9 ,]+\))?(?:\[\])?(?: unsigned)?$`)
var schemaWordPattern = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*$`)

func schemaColumnAutomatic(col map[string]any) bool {
	extra := strings.ToLower(str(col, "extra"))
	return boolValue(mapValue(col, "extra"), "autoIncrement") || len(mapValue(mapValue(col, "extra"), "identity")) > 0 || strings.Contains(extra, "auto_increment") || strings.Contains(extra, "autoincrement") || strings.Contains(extra, "identity") || strings.Contains(extra, "serial")
}

func schemaExpression(value, kind string) error {
	if strings.ContainsRune(value, 0) {
		return errors.New("SQL expression contains NUL")
	}
	_, err := cleanSQL("SELECT "+value, kind)
	return err
}
func schemaLiteral(value, kind string) string {
	if kind == "mysql" {
		// DDL COMMENT clauses require a string token, not a CONVERT expression.
		return "'" + strings.ReplaceAll(strings.ReplaceAll(value, "\\", "\\\\"), "'", "''") + "'"
	}
	b := gridBuilder{options: gridOptions{Kind: kind}}
	s, _ := b.literal(value, gridColumn{Type: "text"})
	return s
}
func schemaColumnDefinition(kind string, col map[string]any, inlinePrimary bool) (string, error) {
	name := str(col, "name")
	if err := compareIdentifier(name); err != nil {
		return "", err
	}
	typ := strings.TrimSpace(str(col, "data_type"))
	if typ == "" {
		typ = str(col, "dataType")
	}
	if !schemaTypePattern.MatchString(typ) {
		return "", fmt.Errorf("Invalid or unsupported column type %q", typ)
	}
	definition := quoteSQLName(name, kind) + " " + typ
	extra := strings.ToLower(str(col, "extra"))
	auto := strings.Contains(extra, "auto_increment") || strings.Contains(extra, "autoincrement")
	editableExtra := mapValue(col, "extra")
	if boolValue(editableExtra, "autoIncrement") {
		auto = true
	}
	if kind == "postgres" && auto {
		if !strings.Contains(strings.ToLower(typ), "serial") {
			definition += " GENERATED BY DEFAULT AS IDENTITY"
		}
	}
	if identity := mapValue(editableExtra, "identity"); kind == "postgres" && len(identity) > 0 {
		generation := strings.ToUpper(str(identity, "generation"))
		if generation == "" {
			generation = "BY DEFAULT"
		}
		if generation != "ALWAYS" && generation != "BY DEFAULT" {
			return "", errors.New("Invalid identity generation")
		}
		definition += " GENERATED " + generation + " AS IDENTITY"
	}
	nullable := boolValue(col, "is_nullable")
	if _, exists := col["isNullable"]; exists {
		nullable = boolValue(col, "isNullable")
	}
	if !nullable {
		definition += " NOT NULL"
	}
	primary := boolValue(col, "is_primary_key") || boolValue(col, "isPrimaryKey")
	if kind == "sqlite" && inlinePrimary && primary {
		definition += " PRIMARY KEY"
		if auto {
			if !strings.EqualFold(typ, "INTEGER") {
				return "", errors.New("SQLite AUTOINCREMENT requires INTEGER PRIMARY KEY")
			}
			definition += " AUTOINCREMENT"
		}
	}
	defaultValue := strings.TrimSpace(str(col, "column_default"))
	if _, exists := col["defaultValue"]; exists {
		defaultValue = strings.TrimSpace(str(col, "defaultValue"))
	}
	if defaultValue != "" {
		if err := schemaExpression(defaultValue, kind); err != nil {
			return "", errors.New("Default must be one SQL expression")
		}
		definition += " DEFAULT " + defaultValue
	}
	if kind == "mysql" {
		if auto {
			definition += " AUTO_INCREMENT"
		}
		if boolValue(editableExtra, "onUpdateCurrentTimestamp") {
			definition += " ON UPDATE CURRENT_TIMESTAMP"
		}
		for _, pair := range [][2]string{{"character_set", "CHARACTER SET"}, {"collation", "COLLATE"}} {
			v := str(col, pair[0])
			if pair[0] == "character_set" && v == "" {
				v = str(col, "characterSet")
			}
			if v != "" {
				if !schemaWordPattern.MatchString(v) {
					return "", errors.New("Invalid character set or collation")
				}
				definition += " " + pair[1] + " " + v
			}
		}
		if comment := str(col, "comment"); comment != "" {
			definition += " COMMENT " + schemaLiteral(comment, kind)
		}
	}
	return definition, nil
}
func schemaForeignKeyDefinition(kind string, fk map[string]any) (string, error) {
	name, column, refColumn := str(fk, "name"), str(fk, "column"), str(fk, "ref_column")
	if refColumn == "" {
		refColumn = str(fk, "refColumn")
	}
	refTable := str(fk, "ref_table")
	if refTable == "" {
		refTable = str(fk, "refTable")
	}
	refSchema := str(fk, "ref_schema")
	if refSchema == "" {
		refSchema = str(fk, "refSchema")
	}
	columns, refColumns := compareStrings(fk["columns"]), compareStrings(fk["ref_columns"])
	if len(refColumns) == 0 {
		refColumns = compareStrings(fk["refColumns"])
	}
	if len(columns) == 0 {
		columns = []string{column}
	}
	if len(refColumns) == 0 {
		refColumns = []string{refColumn}
	}
	if len(columns) != len(refColumns) {
		return "", errors.New("Foreign key columns and referenced columns must have the same width")
	}
	for _, n := range append(append([]string{name}, columns...), refColumns...) {
		if err := compareIdentifier(n); err != nil {
			return "", err
		}
	}
	target, err := compareTable(kind, refSchema, refTable)
	if err != nil {
		return "", err
	}
	quotedColumns, quotedRefs := []string{}, []string{}
	for i, c := range columns {
		quotedColumns = append(quotedColumns, quoteSQLName(c, kind))
		quotedRefs = append(quotedRefs, quoteSQLName(refColumns[i], kind))
	}
	sql := "CONSTRAINT " + quoteSQLName(name, kind) + " FOREIGN KEY (" + strings.Join(quotedColumns, ", ") + ") REFERENCES " + target + " (" + strings.Join(quotedRefs, ", ") + ")"
	match := strings.ToUpper(str(fk, "match_type"))
	if match == "" {
		match = strings.ToUpper(str(fk, "matchType"))
	}
	if kind == "postgres" && match != "" && match != "SIMPLE" {
		if match != "FULL" {
			return "", errors.New("Unsupported foreign key match type")
		}
		sql += " MATCH FULL"
	}
	for _, pair := range [][3]string{{"on_update", "onUpdate", "ON UPDATE"}, {"on_delete", "onDelete", "ON DELETE"}} {
		action := strings.ToUpper(str(fk, pair[0]))
		if action == "" {
			action = strings.ToUpper(str(fk, pair[1]))
		}
		if action != "" {
			switch action {
			case "NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT":
			default:
				return "", errors.New("Invalid foreign key referential action")
			}
			sql += " " + pair[2] + " " + action
		}
	}
	if kind != "mysql" && boolValue(fk, "deferrable") {
		sql += " DEFERRABLE"
		if boolValue(fk, "initially_deferred") || boolValue(fk, "initiallyDeferred") {
			sql += " INITIALLY DEFERRED"
		}
	}
	return sql, nil
}
func schemaIndexSQL(kind, schema, table string, idx map[string]any) (string, error) {
	if boolValue(idx, "is_primary") || boolValue(idx, "isPrimary") {
		return "", nil
	}
	name := str(idx, "name")
	if err := compareIdentifier(name); err != nil {
		return "", err
	}
	target, err := compareTable(kind, schema, table)
	if err != nil {
		return "", err
	}
	columns := compareStrings(idx["columns"])
	if len(columns) == 0 {
		return "", errors.New("Index columns are required")
	}
	quoted := []string{}
	for _, c := range columns {
		if err = compareIdentifier(c); err != nil {
			return "", err
		}
		quoted = append(quoted, quoteSQLName(c, kind))
	}
	unique := ""
	if boolValue(idx, "is_unique") || boolValue(idx, "isUnique") {
		unique = "UNIQUE "
	}
	concurrent := ""
	if boolValue(idx, "concurrently") {
		if kind != "postgres" {
			return "", errors.New("Concurrent indexes require PostgreSQL")
		}
		concurrent = "CONCURRENTLY "
	}
	indexName := quoteSQLName(name, kind)
	if kind == "sqlite" && schema != "" {
		indexName = quoteSQLName(schema, kind) + "." + indexName
		target = quoteSQLName(table, kind)
	}
	sql := "CREATE " + unique + "INDEX " + concurrent + indexName + " ON " + target
	method := str(idx, "index_type")
	if method == "" {
		method = str(idx, "indexType")
	}
	if method != "" && kind == "postgres" {
		if !schemaWordPattern.MatchString(method) {
			return "", errors.New("Invalid index method")
		}
		sql += " USING " + method
	}
	sql += " (" + strings.Join(quoted, ", ") + ")"
	included := compareStrings(idx["included_columns"])
	if len(included) == 0 {
		included = compareStrings(idx["includedColumns"])
	}
	if len(included) > 0 {
		if kind != "postgres" {
			return "", errors.New("Included index columns require PostgreSQL")
		}
		q := []string{}
		for _, c := range included {
			if err = compareIdentifier(c); err != nil {
				return "", err
			}
			q = append(q, quoteSQLName(c, kind))
		}
		sql += " INCLUDE (" + strings.Join(q, ", ") + ")"
	}
	filter := str(idx, "filter")
	if filter != "" {
		if kind == "mysql" {
			return "", errors.New("MySQL does not support partial indexes")
		}
		if err = schemaExpression(filter, kind); err != nil {
			return "", err
		}
		sql += " WHERE " + filter
	}
	return sql + ";", nil
}
func schemaCreateFromColumns(kind, schema, table string, columns, indexes, fks []map[string]any) ([]string, error) {
	target, err := compareTable(kind, schema, table)
	if err != nil {
		return nil, err
	}
	if len(columns) == 0 {
		return nil, errors.New("A table requires at least one column")
	}
	primary := []string{}
	for _, col := range columns {
		if boolValue(col, "is_primary_key") || boolValue(col, "isPrimaryKey") {
			primary = append(primary, quoteSQLName(str(col, "name"), kind))
		}
	}
	for _, idx := range indexes {
		if boolValue(idx, "is_primary") || boolValue(idx, "isPrimary") {
			primary = []string{}
			for _, c := range compareStrings(idx["columns"]) {
				primary = append(primary, quoteSQLName(c, kind))
			}
		}
	}
	defs := []string{}
	seen := map[string]bool{}
	inlinePrimary := false
	for _, col := range columns {
		name := str(col, "name")
		if seen[name] {
			return nil, errors.New("Duplicate column name")
		}
		seen[name] = true
		d, err := schemaColumnDefinition(kind, col, len(primary) == 1)
		if err != nil {
			return nil, err
		}
		defs = append(defs, d)
		if kind == "sqlite" && len(primary) == 1 && (boolValue(col, "is_primary_key") || boolValue(col, "isPrimaryKey")) {
			inlinePrimary = true
		}
	}
	if len(primary) > 0 && !inlinePrimary {
		defs = append(defs, "PRIMARY KEY ("+strings.Join(primary, ", ")+")")
	}
	for _, fk := range fks {
		d, err := schemaForeignKeyDefinition(kind, fk)
		if err != nil {
			return nil, err
		}
		defs = append(defs, d)
	}
	statements := []string{"CREATE TABLE " + target + " (\n  " + strings.Join(defs, ",\n  ") + "\n);"}
	for _, idx := range indexes {
		sql, err := schemaIndexSQL(kind, schema, table, idx)
		if err != nil {
			return nil, err
		}
		if sql != "" {
			statements = append(statements, sql)
		}
	}
	if kind == "postgres" {
		for _, col := range columns {
			if comment := str(col, "comment"); comment != "" {
				statements = append(statements, "COMMENT ON COLUMN "+target+"."+quoteSQLName(str(col, "name"), kind)+" IS "+schemaLiteral(comment, kind)+";")
			}
		}
	}
	return statements, nil
}
func schemaAlterColumn(kind, schema, table string, col, original map[string]any) ([]string, error) {
	target, err := compareTable(kind, schema, table)
	if err != nil {
		return nil, err
	}
	name, oldName := str(col, "name"), str(original, "name")
	if oldName == "" {
		oldName = name
	}
	if err = compareIdentifier(name); err != nil {
		return nil, err
	}
	definition, err := schemaColumnDefinition(kind, col, false)
	if err != nil {
		return nil, err
	}
	if len(original) == 0 {
		return []string{"ALTER TABLE " + target + " ADD COLUMN " + definition + ";"}, nil
	}
	if compareEqual(col, original) {
		return []string{}, nil
	}
	out := []string{}
	if kind == "mysql" {
		return []string{"ALTER TABLE " + target + " CHANGE COLUMN " + quoteSQLName(oldName, kind) + " " + definition + ";"}, nil
	}
	if name != oldName {
		out = append(out, "ALTER TABLE "+target+" RENAME COLUMN "+quoteSQLName(oldName, kind)+" TO "+quoteSQLName(name, kind)+";")
	}
	if kind == "sqlite" {
		return nil, errors.New("SQLite column modifications require a verified table rebuild preview")
	}
	column := quoteSQLName(name, kind)
	if !strings.EqualFold(str(col, "data_type"), str(original, "data_type")) {
		out = append(out, "ALTER TABLE "+target+" ALTER COLUMN "+column+" TYPE "+str(col, "data_type")+" USING "+column+"::"+str(col, "data_type")+";")
	}
	if boolValue(col, "is_nullable") != boolValue(original, "is_nullable") {
		action := "SET NOT NULL"
		if boolValue(col, "is_nullable") {
			action = "DROP NOT NULL"
		}
		out = append(out, "ALTER TABLE "+target+" ALTER COLUMN "+column+" "+action+";")
	}
	if !compareEqual(col["column_default"], original["column_default"]) {
		action := "DROP DEFAULT"
		if value := str(col, "column_default"); value != "" {
			action = "SET DEFAULT " + value
		}
		out = append(out, "ALTER TABLE "+target+" ALTER COLUMN "+column+" "+action+";")
	}
	if !compareEqual(col["comment"], original["comment"]) {
		value := "NULL"
		if col["comment"] != nil {
			value = schemaLiteral(str(col, "comment"), kind)
		}
		out = append(out, "COMMENT ON COLUMN "+target+"."+column+" IS "+value+";")
	}
	return out, nil
}
func editableColumnMetadata(col map[string]any) map[string]any {
	m := map[string]any{"name": col["name"], "data_type": col["dataType"], "is_nullable": col["isNullable"], "is_primary_key": col["isPrimaryKey"], "comment": col["comment"], "extra": col["extra"], "character_set": col["characterSet"], "collation": col["collation"]}
	if d := str(col, "defaultValue"); d != "" {
		m["column_default"] = d
	}
	return m
}
func advancedStructure(p map[string]any, create bool) (map[string]any, error) {
	kind, err := compareKind(str(p, "databaseType"))
	if err != nil {
		return nil, err
	}
	schema, table := str(p, "schema"), str(p, "tableName")
	target, err := compareTable(kind, schema, table)
	if err != nil {
		return nil, err
	}
	columns := compareList(p["columns"])
	indexes := compareList(p["indexes"])
	fks := compareList(p["foreignKeys"])
	statements := []string{}
	warnings := []string{}
	activeCols, activeIdx, activeFK := []map[string]any{}, []map[string]any{}, []map[string]any{}
	for _, c := range columns {
		if !boolValue(c, "markedForDrop") {
			activeCols = append(activeCols, editableColumnMetadata(c))
		}
	}
	for _, i := range indexes {
		if !boolValue(i, "markedForDrop") {
			activeIdx = append(activeIdx, i)
		}
	}
	for _, f := range fks {
		if !boolValue(f, "markedForDrop") {
			activeFK = append(activeFK, f)
		}
	}
	if create {
		statements, err = schemaCreateFromColumns(kind, schema, table, activeCols, activeIdx, activeFK)
		if err != nil {
			return nil, err
		}
		if kind == "mysql" {
			suffix := ""
			if engine := str(p, "mysqlEngine"); engine != "" {
				if !schemaWordPattern.MatchString(engine) {
					return nil, errors.New("Invalid MySQL engine")
				}
				suffix += " ENGINE=" + engine
			}
			if comment := str(p, "tableComment"); comment != "" {
				suffix += " COMMENT=" + schemaLiteral(comment, kind)
			}
			statements[0] = strings.TrimSuffix(statements[0], ";") + suffix + ";"
		}
	} else {
		for _, c := range columns {
			original := mapValue(c, "original")
			if boolValue(c, "markedForDrop") {
				if len(original) > 0 {
					statements = append(statements, "ALTER TABLE "+target+" DROP COLUMN "+quoteSQLName(str(original, "name"), kind)+";")
				}
				continue
			}
			metadata := editableColumnMetadata(c)
			if len(original) > 0 {
				same := true
				for _, k := range []string{"name", "data_type", "is_nullable", "column_default", "comment", "character_set", "collation"} {
					if k == "is_nullable" {
						if boolValue(metadata, k) != boolValue(original, k) {
							same = false
						}
					} else if str(metadata, k) != str(original, k) {
						same = false
					}
				}
				if schemaColumnAutomatic(metadata) != schemaColumnAutomatic(original) {
					same = false
				}
				if same {
					continue
				}
			}
			sql, e := schemaAlterColumn(kind, schema, table, metadata, original)
			if e != nil {
				return nil, e
			}
			statements = append(statements, sql...)
		}
		for _, idx := range indexes {
			original := mapValue(idx, "original")
			changed := len(original) > 0 && (str(idx, "name") != str(original, "name") || !compareEqual(idx["columns"], original["columns"]) || boolValue(idx, "isUnique") != boolValue(original, "is_unique") || str(idx, "filter") != str(original, "filter") || str(idx, "indexType") != str(original, "index_type"))
			if boolValue(idx, "markedForDrop") || changed {
				if len(original) > 0 {
					drop, err := schemaDropIndex(kind, schema, table, original)
					if err != nil {
						return nil, err
					}
					statements = append(statements, drop)
				}
			}
			if !boolValue(idx, "markedForDrop") && (len(original) == 0 || changed) {
				if boolValue(idx, "isPrimary") {
					if kind == "sqlite" {
						return nil, errors.New("SQLite primary key changes require a table rebuild")
					}
					q := []string{}
					for _, c := range compareStrings(idx["columns"]) {
						q = append(q, quoteSQLName(c, kind))
					}
					statements = append(statements, "ALTER TABLE "+target+" ADD PRIMARY KEY ("+strings.Join(q, ", ")+");")
				} else {
					if boolValue(p, "partitioned") && boolValue(idx, "concurrently") {
						return nil, errors.New("CREATE INDEX CONCURRENTLY is unavailable on partitioned parents")
					}
					sql, err := schemaIndexSQL(kind, schema, table, idx)
					if err != nil {
						return nil, err
					}
					statements = append(statements, sql)
				}
			}
		}
		for _, fk := range fks {
			original := mapValue(fk, "original")
			changed := len(original) > 0 && (str(fk, "name") != str(original, "name") || str(fk, "column") != str(original, "column") || str(fk, "refTable") != str(original, "ref_table") || str(fk, "refColumn") != str(original, "ref_column") || str(fk, "onUpdate") != str(original, "on_update") || str(fk, "onDelete") != str(original, "on_delete"))
			if (boolValue(fk, "markedForDrop") || changed) && len(original) > 0 {
				if kind == "sqlite" {
					return nil, errors.New("SQLite foreign key edits require a table rebuild")
				}
				keyword := "DROP CONSTRAINT"
				if kind == "mysql" {
					keyword = "DROP FOREIGN KEY"
				}
				statements = append(statements, "ALTER TABLE "+target+" "+keyword+" "+quoteSQLName(str(original, "name"), kind)+";")
			}
			if !boolValue(fk, "markedForDrop") && (len(original) == 0 || changed) {
				if kind == "sqlite" {
					return nil, errors.New("SQLite foreign key edits require a table rebuild")
				}
				definition, err := schemaForeignKeyDefinition(kind, fk)
				if err != nil {
					return nil, err
				}
				statements = append(statements, "ALTER TABLE "+target+" ADD "+definition+";")
			}
		}
	}
	for _, trigger := range compareList(p["triggers"]) {
		original := mapValue(trigger, "original")
		changed := len(original) > 0 && (str(trigger, "statement") != str(original, "statement") || str(trigger, "name") != str(original, "name"))
		if (boolValue(trigger, "markedForDrop") || changed) && len(original) > 0 {
			drop := "DROP TRIGGER " + quoteSQLName(str(original, "name"), kind)
			if kind == "postgres" {
				drop += " ON " + target
			}
			statements = append(statements, drop+";")
		}
		if !boolValue(trigger, "markedForDrop") && (create || len(original) == 0 || changed) {
			sql := str(trigger, "statement")
			if !strings.HasPrefix(strings.ToUpper(strings.TrimSpace(sql)), "CREATE ") {
				timing, event := strings.ToUpper(str(trigger, "timing")), strings.ToUpper(str(trigger, "event"))
				if timing != "BEFORE" && timing != "AFTER" && timing != "INSTEAD OF" {
					return nil, errors.New("Invalid trigger timing")
				}
				if event != "INSERT" && event != "UPDATE" && event != "DELETE" {
					return nil, errors.New("Invalid trigger event")
				}
				sql = "CREATE TRIGGER " + quoteSQLName(str(trigger, "name"), kind) + " " + timing + " " + event + " ON " + target + " FOR EACH ROW " + sql
			}
			sql, err = cleanSQL(sql, kind)
			if err != nil {
				return nil, err
			}
			statements = append(statements, sql+";")
		}
	}
	if kind == "postgres" && (create || str(p, "tableComment") != str(p, "originalTableComment")) {
		statements = append(statements, "COMMENT ON TABLE "+target+" IS "+schemaLiteral(str(p, "tableComment"), kind)+";")
	}
	if kind == "mysql" && !create && str(p, "tableComment") != str(p, "originalTableComment") {
		statements = append(statements, "ALTER TABLE "+target+" COMMENT="+schemaLiteral(str(p, "tableComment"), kind)+";")
	}
	if kind == "sqlite" && str(p, "tableComment") != "" {
		warnings = append(warnings, "SQLite does not store database table or column comments")
	}
	return map[string]any{"statements": statements, "warnings": warnings}, nil
}
func schemaDropIndex(kind, schema, table string, index map[string]any) (string, error) {
	name := str(index, "name")
	if boolValue(index, "is_primary") || boolValue(index, "isPrimary") {
		target, err := compareTable(kind, schema, table)
		if err != nil {
			return "", err
		}
		if kind == "mysql" {
			return "ALTER TABLE " + target + " DROP PRIMARY KEY;", nil
		}
		if kind == "sqlite" {
			return "", errors.New("SQLite primary indexes require table rebuild")
		}
		return "ALTER TABLE " + target + " DROP CONSTRAINT " + quoteSQLName(name, kind) + ";", nil
	}
	target, err := compareTable(kind, schema, name)
	if err != nil {
		return "", err
	}
	if kind == "mysql" {
		tableName, err := compareTable(kind, schema, table)
		if err != nil {
			return "", err
		}
		return "DROP INDEX " + quoteSQLName(name, kind) + " ON " + tableName + ";", nil
	}
	return "DROP INDEX " + target + ";", nil
}
func (s *Server) handleAdvancedSQL(w http.ResponseWriter, r *http.Request, p map[string]any) bool {
	if s.handleSQLiteStructure(w, r, p) || s.handleAdvancedExplain(w, r, p) {
		return true
	}
	if s.handleAdvancedAdmin(w, r, p) || s.handleAdvancedGrid(w, r, p) || s.handleAdvancedExport(w, r, p) {
		return true
	}
	var result any
	var err error
	o := mapValue(p, "options")
	switch r.URL.Path {
	case "/api/query/build-create-table-sql":
		result, err = advancedStructure(o, true)
	case "/api/query/build-table-structure-change-sql":
		result, err = advancedStructure(o, false)
	case "/api/query/build-single-column-alter-sql":
		o["columns"] = []any{o["column"]}
		result, err = advancedStructure(o, false)
	case "/api/query/build-table-owner-change-sql":
		if str(o, "databaseType") != "postgres" {
			err = errors.New("Owner changes require PostgreSQL")
		} else {
			var target string
			target, err = compareTable("postgres", str(o, "schema"), str(o, "tableName"))
			if err == nil {
				err = compareIdentifier(str(o, "owner"))
			}
			if err == nil {
				statements := []string{}
				if str(o, "owner") != str(o, "originalOwner") {
					statements = append(statements, "ALTER TABLE "+target+" OWNER TO "+quoteSQLName(str(o, "owner"), "postgres")+";")
				}
				result = map[string]any{"statements": statements, "warnings": []string{}}
			}
		}
	case "/api/query/build-create-partitioned-table-sql":
		if str(o, "databaseType") != "postgres" {
			err = errors.New("Partitioned table creation requires PostgreSQL")
		} else {
			var built map[string]any
			built, err = advancedStructure(o, true)
			if err == nil {
				partition := mapValue(p, "partitioning")
				kind := strings.ToUpper(str(partition, "kind"))
				if kind != "RANGE" && kind != "LIST" && kind != "HASH" {
					err = errors.New("Invalid partitioning kind")
				} else {
					expression := str(partition, "expression")
					if expression == "" {
						q := []string{}
						for _, c := range compareStrings(partition["columns"]) {
							if err = compareIdentifier(c); err != nil {
								break
							}
							q = append(q, quoteSQLName(c, "postgres"))
						}
						expression = strings.Join(q, ", ")
					}
					if expression == "" {
						err = errors.New("Partition columns or expression are required")
					} else if err = schemaExpression(expression, "postgres"); err == nil {
						statements := compareStrings(built["statements"])
						statements[0] = strings.TrimSuffix(statements[0], ";") + " PARTITION BY " + kind + " (" + expression + ");"
						built["statements"] = statements
						result = built
					}
				}
			}
		}
	case "/api/query/build-table-partition-operation-sql":
		result, err = advancedPartitions(o)
	default:
		return false
	}
	if r.Method != "POST" {
		writeError(w, 405, "Method not allowed")
	} else if err != nil {
		writeError(w, 400, err.Error())
	} else {
		writeJSON(w, 200, result)
	}
	return true
}
func advancedPartitionBound(p map[string]any) (string, error) {
	switch str(p, "kind") {
	case "default":
		return "DEFAULT", nil
	case "hash":
		m, r := numberValue(p, "modulus", 0), numberValue(p, "remainder", -1)
		if m <= 0 || r < 0 || r >= m {
			return "", errors.New("Hash partition requires positive modulus and remainder below modulus")
		}
		return fmt.Sprintf("FOR VALUES WITH (MODULUS %d, REMAINDER %d)", m, r), nil
	case "list":
		v := compareStrings(p["values"])
		if len(v) == 0 {
			return "", errors.New("List values are required")
		}
		for _, s := range v {
			if err := schemaExpression(s, "postgres"); err != nil {
				return "", err
			}
		}
		return "FOR VALUES IN (" + strings.Join(v, ", ") + ")", nil
	case "range":
		from, to := compareStrings(p["from"]), compareStrings(p["to"])
		if len(from) == 0 || len(from) != len(to) {
			return "", errors.New("Range bounds must have matching nonzero widths")
		}
		for _, s := range append(from, to...) {
			if s != "MINVALUE" && s != "MAXVALUE" {
				if err := schemaExpression(s, "postgres"); err != nil {
					return "", err
				}
			}
		}
		return "FOR VALUES FROM (" + strings.Join(from, ", ") + ") TO (" + strings.Join(to, ", ") + ")", nil
	}
	return "", errors.New("Invalid partition bound")
}
func advancedPartitions(o map[string]any) (map[string]any, error) {
	if str(o, "databaseType") != "postgres" {
		return nil, errors.New("Partition operations require PostgreSQL")
	}
	statements := []string{}
	for _, op := range compareList(o["operations"]) {
		parentSchema, parentTable := str(op, "parentSchema"), str(op, "parentTable")
		if parentSchema == "" {
			parentSchema = str(o, "schema")
		}
		if parentTable == "" {
			parentTable = str(o, "tableName")
		}
		parent, err := compareTable("postgres", parentSchema, parentTable)
		if err != nil {
			return nil, err
		}
		schema := str(op, "schema")
		if schema == "" {
			schema = parentSchema
		}
		child, err := compareTable("postgres", schema, str(op, "name"))
		if err != nil {
			return nil, err
		}
		kind := str(op, "kind")
		switch kind {
		case "create", "attach":
			bound, err := advancedPartitionBound(mapValue(op, "bound"))
			if err != nil {
				return nil, err
			}
			if boolValue(op, "concurrently") {
				return nil, errors.New("Only partition detach supports CONCURRENTLY")
			}
			if kind == "create" {
				statements = append(statements, "CREATE TABLE "+child+" PARTITION OF "+parent+" "+bound+";")
			} else {
				statements = append(statements, "ALTER TABLE "+parent+" ATTACH PARTITION "+child+" "+bound+";")
			}
		case "detach":
			sql := "ALTER TABLE " + parent + " DETACH PARTITION " + child
			if boolValue(op, "concurrently") {
				sql += " CONCURRENTLY"
			}
			statements = append(statements, sql+";")
		case "drop":
			if boolValue(op, "concurrently") {
				return nil, errors.New("Drop partition does not support CONCURRENTLY")
			}
			statements = append(statements, "DROP TABLE "+child+";")
		default:
			return nil, errors.New("Invalid partition operation")
		}
	}
	return map[string]any{"statements": statements, "warnings": []string{}}, nil
}
